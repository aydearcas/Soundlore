"""Package the viewer for Pages; optionally rebuild all data from local sources."""
import argparse
from pathlib import Path
import shutil
import subprocess
import sys

from validate_site import ASSETS, validate

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rebuild', action='store_true',
                        help='Rebuild JSON and the map first (requires requirements.txt)')
    args = parser.parse_args()
    if args.rebuild:
        for module in ('numpy', 'sklearn'):
            try:
                __import__(module)
            except ImportError:
                parser.error('Install rebuild dependencies first: python -m pip install -r requirements.txt')
        for script in ('build_concepts.py', 'build_genres.py', 'verify.py', 'build_map.py'):
            subprocess.run([sys.executable, '-X', 'utf8', str(ROOT / 'build' / script)],
                           cwd=ROOT, check=True)
        for name in ASSETS:
            shutil.copy2(ROOT / 'build' / name, ROOT / 'viewer' / name)

    validate()
    destination = ROOT / 'dist'
    # A dedicated output folder prevents stale files from entering the deployment.
    if destination.is_symlink():
        raise ValueError('dist must not be a symbolic link')
    if destination.exists():
        if not (destination / '.music-thesaurus-output').is_file():
            raise ValueError('Existing dist is not a generated Music Thesaurus package')
        shutil.rmtree(destination)
    destination.mkdir()
    for name in ('index.html', *ASSETS):
        shutil.copy2(ROOT / 'viewer' / name, destination / name)
    (destination / '.nojekyll').touch()
    (destination / '.music-thesaurus-output').write_text('Generated by build/package.py\n', encoding='utf-8')
    validate(destination)
    print(f'Pages artifact ready: {destination}')


if __name__ == '__main__':
    main()
