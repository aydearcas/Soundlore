"""Package the site in viewer/ for GitHub Pages: validate it and copy it to dist/.

Used by .github/workflows/pages.yml on every push. To rebuild the data first (needs
requirements.txt): python build/package.py --rebuild
"""
import argparse
from pathlib import Path
import shutil
import subprocess
import sys

from validate_site import ASSETS, PAGES, validate

ROOT = Path(__file__).resolve().parents[1]
MARK = '.soundlore-output'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rebuild', action='store_true',
                        help='Rebuild the concepts, genres, map and layers first (requires requirements.txt); the artists are rebuilt with build/build_artists.py')
    args = parser.parse_args()
    if args.rebuild:
        for module in ('numpy', 'sklearn'):
            try:
                __import__(module)
            except ImportError:
                parser.error('Install rebuild dependencies first: python -m pip install -r requirements.txt')
        for script in ('build_concepts.py', 'export_skos.py', 'build_genres.py', 'verify.py', 'build_map.py',
                       'build_layers.py', 'sync_viewer.py'):
            subprocess.run([sys.executable, '-X', 'utf8', str(ROOT / 'build' / script)], cwd=ROOT, check=True)

    validate()
    destination = ROOT / 'dist'
    # a dedicated output folder keeps stale files out of the deployment
    if destination.is_symlink():
        raise ValueError('dist must not be a symbolic link')
    if destination.exists():
        if not ((destination / MARK).is_file() or (destination / '.music-thesaurus-output').is_file()):
            raise ValueError('Existing dist is not a generated Soundlore package')
        shutil.rmtree(destination)
    destination.mkdir()
    for name in PAGES + ASSETS:
        shutil.copy2(ROOT / 'viewer' / name, destination / name)
    (destination / '.nojekyll').touch()
    (destination / MARK).write_text('Generated by build/package.py\n', encoding='utf-8')
    validate(destination)
    print(f'Pages artifact ready: {destination}')


if __name__ == '__main__':
    main()
